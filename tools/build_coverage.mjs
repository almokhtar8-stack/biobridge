#!/usr/bin/env node
/* Builds docs/COVERAGE.md, the educational coverage matrix, from the content files.
   Usage: node tools/build_coverage.mjs
   Re-run after changing lessons, questions, missions or generators so the matrix never drifts from the site. */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const contentFiles = [...html.matchAll(/<script src="(content\/[^"]+\.js)"/g)].map((m) => m[1]);
const ctx = { window: {}, console };
ctx.window.window = ctx.window;
vm.createContext(ctx);
for (const f of contentFiles) {
  const code = fs.readFileSync(path.join(ROOT, f), 'utf8');
  vm.runInContext(code.replace(/^window\.BB = window\.BB \|\| \{\};/m, 'var BB = window.BB = window.BB || {};'), ctx, { filename: f });
}
const BB = ctx.window.BB;

// Generator metadata is read from js/generators.js without executing it.
const genSrc = fs.readFileSync(path.join(ROOT, 'js/generators.js'), 'utf8');
const generators = [...genSrc.matchAll(/add\('([a-z0-9-]+)',\s*\{\s*obj:\s*\[([^\]]*)\],\s*level:\s*(\d)\s*,\s*lesson:\s*'([^']+)'[^}]*label:\s*'([^']+)'/g)]
  .map((m) => ({ key: m[1], obj: m[2].split(',').map((s) => s.trim().replace(/'/g, '')).filter(Boolean), level: +m[3], lesson: m[4], label: m[5] }));

const meta = BB.lessonMeta;
const lessons = Object.fromEntries(BB.lessons.map((L) => [L.id, L]));
const questions = BB.questions;
const objectives = BB.objectives;
const courseName = { kaust: 'KAUST Fundamental Skills in Bioinformatics', rice: 'Rice Python Programming Essentials', ibm: 'IBM Hands-on Introduction to Linux Commands and Shell Scripting' };
const alignLabel = { core: 'Core', support: 'Support', beyond: 'Beyond' };

const TRY_LABEL = {
  terminal: 'terminal mission', trace: 'step-through trace', predict: 'predict the output', parsons: 'arrange the code', debug: 'find the bug'
};
const WIDGET_LABEL = {
  dogma: 'DNA to protein editor', expression: 'cell-type expression explorer', filetree: 'path explorer', datatable: 'linked dataset reader',
  scale: 'data-size estimator', journey: 'discovery journey', cron: 'cron explainer', pyrun: 'real Python editor', fastq: 'FASTQ decoder',
  countmatrix: 'count-matrix explorer', normalization: 'normalization lab', variability: 'replicates and t-test lab', log2: 'log2 scale lab',
  correlation: 'correlation lab', pvalues: 'multiple-testing simulator', rnaseq: 'guided RNA-seq experiment', singlecell: 'single-cell lab',
  methods: 'method-choice scenarios'
};
function tryLabel(L) {
  const t = L && L.try;
  if (!t) return 'none';
  if (t.kind === 'widget') {
    const extra = t.widget === 'singlecell' && t.props && t.props.mode ? ` (${t.props.mode === 'qc' ? 'quality control' : 'clusters'})` : '';
    return (WIDGET_LABEL[t.widget] || t.widget) + extra;
  }
  if (t.kind === 'terminal') return `${TRY_LABEL.terminal} (${(BB.missions[t.mission] || { steps: [] }).steps.length} steps)`;
  if (t.kind === 'trace') return `${TRY_LABEL.trace} (${(BB.pyPrograms[t.program] || {}).title || t.program})`;
  return TRY_LABEL[t.kind] || t.kind;
}
const qByLesson = (id) => questions.filter((q) => q.lesson === id);
const qByObj = (o) => questions.filter((q) => q.obj.includes(o));
const lvl = (qs) => [1, 2, 3].map((n) => qs.filter((q) => q.level === n).length);
const lessonsForObj = (o) => Object.keys(meta).filter((id) => meta[id].obj.includes(o));
const gensForObj = (o) => generators.filter((g) => g.obj.includes(o));
const lessonLink = (id) => `${meta[id].title} (\`${id}\`)`;

const out = [];
const P = (s = '') => out.push(s);
const totalChecks = BB.lessons.reduce((n, L) => n + (L.check ? L.check.length : 0), 0);
const fCount = (f) => questions.filter((q) => (objectives[q.obj[0]] || {}).f === f).length;

P('# BioBridge 2.0 educational coverage matrix');
P();
P('This file is generated by `node tools/build_coverage.mjs` from the content files, so the numbers match the site exactly. Course module titles and summaries come from the public Coursera course pages (checked 7 November 2026). BioBridge is an independent study companion: nothing here is an official KAUST Academy, KAUST, Rice, IBM or Coursera blueprint, and no real assessment questions were used or seen.');
P();
P('## How to read it');
P();
P('- **Core**: the lesson teaches something the linked course module teaches.');
P('- **Support**: background the courses assume or only touch briefly (for example the biology behind RNA-seq).');
P('- **Beyond**: goes past the three courses. Learners see a "Beyond the prerequisites" label on these lessons.');
P('- **Bank L1/L2/L3**: hand-written practice questions at beginner, intermediate and application level. Every option has its own explanation, and every question that contains code was executed with real Python, R or Bash to confirm its answer.');
P('- **Generated**: question templates that produce fresh numbers or sequences each time (seeded, so a session can be reproduced). Their answers are computed, and the code-based ones were executed during testing.');
P('- Lesson checks (the two or three questions at the end of each lesson) are counted separately from the bank.');
P();
P('## Totals');
P();
P('| Item | Count |');
P('| --- | --- |');
P(`| Foundations | ${BB.foundations.length} (0 to 3) |`);
P(`| Lessons | ${BB.lessons.length} (${['core', 'support', 'beyond'].map((a) => `${Object.values(meta).filter((m) => m.align === a).length} ${a}`).join(', ')}) |`);
P(`| Learning objectives ("I can..." statements) | ${Object.keys(objectives).length} |`);
P(`| Practice bank questions | ${questions.length} (F0 ${fCount('f0')}, F1 ${fCount('f1')}, F2 ${fCount('f2')}, F3 ${fCount('f3')}; levels L1 ${lvl(questions)[0]}, L2 ${lvl(questions)[1]}, L3 ${lvl(questions)[2]}) |`);
P(`| Generated question templates | ${generators.length} |`);
P(`| Lesson check questions | ${totalChecks} |`);
P(`| Terminal missions | ${Object.keys(BB.missions).length} (${Object.values(BB.missions).reduce((n, m) => n + m.steps.length, 0)} steps) |`);
P(`| Recorded Python traces | ${Object.keys(BB.pyPrograms).length} |`);
P(`| Method-choice scenarios | ${(BB.scenarios || []).length} |`);
P(`| Glossary terms | ${BB.glossary.length} |`);
P();

for (const [cid, course] of Object.entries(BB.courses)) {
  P(`## ${courseName[cid]}`);
  P();
  P(`Public course page: ${course.url}`);
  P();
  for (const mod of course.modules) {
    const ids = Object.keys(meta).filter((id) => meta[id].courses.includes(mod.id));
    const objs = [...new Set(ids.flatMap((id) => meta[id].obj))];
    const qs = questions.filter((q) => q.obj.some((o) => objs.includes(o)));
    const gens = generators.filter((g) => g.obj.some((o) => objs.includes(o)));
    P(`### Module ${mod.n}: ${mod.title}`);
    P();
    P(`Course summary: ${mod.summary}`);
    P();
    if (!ids.length) { P('No lesson is mapped to this module.'); P(); continue; }
    P('| Lesson | Alignment | Objectives | Hands-on activity | Bank questions for the lesson |');
    P('| --- | --- | --- | --- | --- |');
    for (const id of ids) {
      const m = meta[id];
      P(`| ${lessonLink(id)} | ${alignLabel[m.align]} | ${m.obj.join(', ')} | ${tryLabel(lessons[id])} | ${qByLesson(id).length} |`);
    }
    P();
    const [a, b, c] = lvl(qs);
    P(`Practice on this module's objectives: ${qs.length} bank questions (L1 ${a}, L2 ${b}, L3 ${c})${gens.length ? ` and ${gens.length} generated template${gens.length === 1 ? '' : 's'} (${gens.map((g) => g.label).join('; ')})` : ''}.`);
    P();
  }
  if (cid === 'ibm') {
    P('Module 4 is a project and exam module. BioBridge does not copy or imitate the graded project or exam. It builds the pieces a scheduled backup script needs: variables, loops and conditions (the scripting missions), packing a folder into a compressed archive (the archive mission), absolute paths, and scheduling a script with output logged (the cron lesson and cron explainer).');
    P();
  }
  if (cid === 'rice') {
    P('The Rice course runs in CodeSkulptor. BioBridge runs real CPython (Pyodide) in the browser, and the essentials unit avoids features CodeSkulptor lacks, such as f-strings. Module 4 date handling is taught with the standard `datetime` module; the course project itself is not reproduced.');
    P();
  }
}

P('## Objective matrix');
P();
P('Every learning objective, where it is taught and how much practice targets it.');
P();
for (const f of BB.foundations) {
  P(`### ${f.short}: ${f.title}`);
  P();
  P('| Objective | Taught in | Bank L1 / L2 / L3 | Generated templates |');
  P('| --- | --- | --- | --- |');
  for (const [oid, o] of Object.entries(objectives)) {
    if (o.f !== f.id) continue;
    const ls = lessonsForObj(oid);
    const [a, b, c] = lvl(qByObj(oid));
    const g = gensForObj(oid);
    P(`| **${oid}** ${o.label} | ${ls.map((id) => `\`${id}\``).join(', ') || 'not taught yet'} | ${a} / ${b} / ${c} | ${g.length ? g.map((x) => x.key).join(', ') : '0'} |`);
  }
  P();
}

P('## Lessons that go beyond the three courses');
P();
for (const [id, m] of Object.entries(meta)) if (m.align === 'beyond') P(`- ${lessonLink(id)}: ${m.obj.map((o) => objectives[o].label.toLowerCase()).join('; ')}.`);
P();
P('These are labelled "Beyond the prerequisites" on the lesson page and in lesson lists. They exist because they connect the course skills to real biological files and workflows. The first two practice core course skills (grep, pipes, Python strings and loops) on biological files, so their questions can appear in mock assessments. Objectives flagged `beyond: true` in `content/curriculum.js` (currently only BI.WORKFLOW) are left out of mocks and appear only in topic practice and review.');
P();

P('## Lessons with no direct course module');
P();
for (const [id, m] of Object.entries(meta)) if (!m.courses.length) P(`- ${lessonLink(id)} (${alignLabel[m.align]})`);
P();

// Companion (2.2): every public course item and the topic that helps with it
P('## Companion topics by course item (BioBridge 2.2)');
P();
P('Item titles are from the public Coursera pages (checked 8 November 2026, `tools/course_items.json`). "Background" marks a topic that gives background for an item rather than its exact subject. Items without a topic are introductions, cheat sheets, summaries, quizzes or project submissions.');
P();
const ITEMS = JSON.parse(fs.readFileSync(path.join(ROOT, 'tools/course_items.json'), 'utf8'));
const topics = BB.companion || [];
let covered = 0, total = 0;
for (const [ck, c] of Object.entries(BB.courses)) {
  P(`### ${c.name} (${c.org})`);
  P();
  for (const m of c.modules) {
    P(`**Module ${m.n}: ${m.title}**`);
    P();
    P('| Course item | Companion topic |');
    P('| --- | --- |');
    for (const item of ITEMS.items[m.id] || []) {
      const ts = topics.filter((t) => (t.lectures || []).includes(item));
      total++; if (ts.length) covered++;
      P(`| ${item.replace(/\|/g, '/')} | ${ts.map((t) => `[${t.title}](../index.html#/c/${t.course}/${t.id})${t.background ? ' (background)' : ''}`).join('; ') || '' } |`);
    }
    const extra = topics.filter((t) => t.module === m.id && !(t.lectures || []).length);
    for (const t of extra) P(`| (module description) | [${t.title}](../index.html#/c/${t.course}/${t.id}) |`);
    P();
  }
}
P(`${covered} of ${total} public course items have at least one Companion topic; ${topics.length} topics in total.`);
P();

// Automatic gap report
P('## Gaps and thin spots');
P();
P('Computed automatically: any objective with fewer than 4 bank questions, or with no application-level (L3) question.');
P();
const thin = Object.entries(objectives).filter(([oid]) => { const [a, b, c] = lvl(qByObj(oid)); return a + b + c < 4 || c === 0; });
if (!thin.length) P('- None. Every objective has at least 4 bank questions and at least one application-level question.');
for (const [oid, o] of thin) { const [a, b, c] = lvl(qByObj(oid)); P(`- **${oid}** ${o.label}: L1 ${a}, L2 ${b}, L3 ${c}.`); }
P();
P('Known gaps that numbers cannot show:');
P();
P('- **RStudio and R Markdown**: explained in words with example code, but there is no R engine in the browser, so R code is shown with its real, pre-computed output rather than run live.');
P('- **Linear models and ANOVA**: covered conceptually with verified R output; there is no interactive ANOVA lab.');
P('- **Networking and package managers** (`ping`, `curl`, `wget`, `apt`): the simulated terminal has no network or installer, so these commands print an explanation instead of running.');
P('- **Vim**: described and compared with nano; the in-browser editor is a simple text box, not a modal editor.');
P('- **Full pipelines** (aligners, quantifiers, DESeq2, Scanpy): described in the workflows lesson and the guided experiment, but not run, because they need real reference genomes and far more memory than a browser offers.');
P('- **Course-specific details** that change between course runs (quiz formats, lab tools, project rubrics) are deliberately not reproduced.');
P();

const file = path.join(ROOT, 'docs/COVERAGE.md');
fs.mkdirSync(path.dirname(file), { recursive: true });
const text = out.join('\n');
if (/[–—]/.test(text)) { console.error('Coverage text contains an en or em dash'); process.exit(1); }
fs.writeFileSync(file, text + '\n');
console.log(`Wrote ${path.relative(ROOT, file)} (${out.length} lines, ${generators.length} generators parsed)`);
