#!/usr/bin/env python3
"""Build the downloadable practice project from the same files the browser terminal uses.

Reads content/vfs.js (generated by tools/build_datasets.py) and writes
  assets/downloads/biobridge-practice.zip
with a top-level folder biobridge-practice/ that mirrors ~/project in the simulation:
README.txt, data/, scripts/ (count_seqs.sh not executable on purpose, line_report.sh executable) and an empty results/.
The archive is reproducible: fixed timestamps, sorted entries, Unix permissions, LF line endings.
Run: python3 tools/build_practice_zip.py
"""
import json, os, re, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOP = "biobridge-practice"
STAMP = (2026, 11, 8, 0, 0, 0)

def load_vfs():
    text = open(os.path.join(ROOT, "content", "vfs.js"), encoding="utf-8").read()
    m = re.search(r"BB\.vfs = (\{.*\});\s*$", text, re.S)
    return json.loads(m.group(1))

def build(out_path):
    vfs = load_vfs()
    base = vfs["home"] + "/project/"
    files = {p[len(base):]: f for p, f in vfs["files"].items() if p.startswith(base)}
    dirs = sorted({d[len(base):] for d in vfs["dirs"] if d.startswith(base)})
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with zipfile.ZipFile(out_path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        def add_dir(rel):
            zi = zipfile.ZipInfo(f"{TOP}/{rel}/" if rel else f"{TOP}/", date_time=STAMP)
            zi.create_system = 3
            zi.external_attr = (0o40755 << 16) | 0x10
            z.writestr(zi, b"")
        add_dir("")
        for d in dirs:
            add_dir(d)
        for rel in sorted(files):
            f = files[rel]
            data = f["c"].replace("\r\n", "\n").encode("utf-8")
            zi = zipfile.ZipInfo(f"{TOP}/{rel}", date_time=STAMP)
            zi.create_system = 3
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = (0o100000 | int(f.get("mode", "644"), 8)) << 16
            z.writestr(zi, data)
    return files, dirs

if __name__ == "__main__":
    out = os.path.join(ROOT, "assets", "downloads", "biobridge-practice.zip")
    files, dirs = build(out)
    print("wrote", out, os.path.getsize(out), "bytes:", len(files), "files,", len(dirs), "folders")
